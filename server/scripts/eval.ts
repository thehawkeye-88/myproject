import { mkdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { scoreCorpus, type Row } from '../src/eval.js';
import { CORPUS } from './corpus.js';

/** `./run eval` — runs the harness in `src/eval.ts` and writes EVAL.md. */

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, '..', '..', 'data', 'eval');
mkdirSync(outDir, { recursive: true });

const { rows, summary } = await scoreCorpus();
const n = summary.fields;
const pct = (k: number) => `${((k / n) * 100).toFixed(1)}%`;

writeFileSync(join(outDir, 'results.json'), JSON.stringify({ summary, rows }, null, 2));

const byDoc = CORPUS.map((s) => {
  const r = rows.filter((x) => x.file === s.file);
  return `| \`${s.file}\` | ${s.layout} | ${r.filter((x) => x.outcome !== 'clean').length} | ${r.filter((x) => x.outcome === 'escaped').length} | ${s.tests} |`;
}).join('\n');

const list = (rs: Row[]) => rs.length
  ? rs.map((r) => `- \`${r.file}\` · **${r.key}** — ${r.why}`).join('\n')
  : '_None._';

writeFileSync(join(here, '..', '..', 'EVAL.md'), `# Evaluation

Generated by \`./run eval\`. Do not edit by hand.

${summary.documents} documents · ${n} fields · ${new Date().toISOString().slice(0, 10)}

## The number that matters

**Escape rate ${pct(summary.escaped)}** — values that were wrong or missing and were
*not* flagged. A reviewer working only the queue would ship these without ever
seeing them. Everything else on this page is secondary to that number.

| | count | share |
|---|---:|---:|
| Correct, not flagged — the reviewer never sees these | ${summary.clean} | ${pct(summary.clean)} |
| Wrong or missing, and flagged — the product working | ${summary.caught} | ${pct(summary.caught)} |
| Correct and flagged because the *document* is inconsistent | ${summary.expected} | ${pct(summary.expected)} |
| Correct but flagged anyway — wasted reviewer attention | ${summary.falseAlarm} | ${pct(summary.falseAlarm)} |
| **Wrong or missing and NOT flagged — escaped** | **${summary.escaped}** | **${pct(summary.escaped)}** |

- **Review load ${(summary.reviewLoad * 100).toFixed(1)}%** — the share of fields a reviewer is asked to look at.
- **Field accuracy ${(summary.accuracy * 100).toFixed(1)}%** — extraction correctness, ignoring flags.
- **Queue precision ${(summary.queuePrecision * 100).toFixed(1)}%** — of everything flagged, the share that deserved it.

## Per document

| file | layout | flagged | escaped | what it tests |
|---|---|---:|---:|---|
${byDoc}

## Every escape

Each of these is a value a reviewer would have shipped without being shown it.

${list(rows.filter((r) => r.outcome === 'escaped'))}

## Every false alarm

Not harmful, but each one spends attention the queue is supposed to save.

${list(rows.filter((r) => r.outcome === 'false_alarm'))}

## Everything the queue caught

${list(rows.filter((r) => r.outcome === 'caught'))}

---

**What this does not prove.** The corpus is generated by \`server/scripts/corpus.ts\`,
written alongside the extractor by the same author. It spans eleven layouts on
purpose, but it cannot falsify rules it was written next to, and a real supplier
will do something nobody here thought of. These numbers bound the product from
above. They are a regression baseline — \`server/test/eval.test.ts\` fails the build
if the escape rate rises — not a measurement of field accuracy in production.
`);

console.log(`\n  ${summary.documents} documents · ${n} fields\n`);
for (const [k, v] of [['clean', summary.clean], ['caught', summary.caught], ['expected', summary.expected], ['false alarm', summary.falseAlarm], ['ESCAPED', summary.escaped]] as const) {
  console.log(`  ${String(k).padEnd(12)} ${String(v).padStart(4)}  ${pct(v as number)}`);
}
console.log(`\n  review load     ${(summary.reviewLoad * 100).toFixed(1)}%`);
console.log(`  field accuracy  ${(summary.accuracy * 100).toFixed(1)}%`);
console.log(`  queue precision ${(summary.queuePrecision * 100).toFixed(1)}%\n`);
for (const r of rows.filter((x) => x.outcome === 'escaped')) console.log(`  ESCAPE  ${r.file}  ${r.key}: ${r.why}`);
console.log(`\n  wrote EVAL.md and data/eval/results.json\n`);
